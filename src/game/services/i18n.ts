export function initializeLanguage(scene: Phaser.Scene): LanguageCode {
  const language = getStoredLanguage();
  scene.registry.set(LANGUAGE_REGISTRY_KEY, language);
  return language;
}

export function getLanguage(source?: Phaser.Scene | LanguageCode | null): LanguageCode {
  if (typeof source === 'string') {
    return normalizeLanguage(source);
  }

  const registryValue = source?.registry.get(LANGUAGE_REGISTRY_KEY);
  if (typeof registryValue === 'string') {
    return normalizeLanguage(registryValue);
  }

  return getStoredLanguage();
}

export function setLanguage(scene: Phaser.Scene, language: LanguageCode): LanguageCode {
  const normalized = normalizeLanguage(language);
  localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
  scene.registry.set(LANGUAGE_REGISTRY_KEY, normalized);
  return normalized;
}

export function t(
  source: Phaser.Scene | LanguageCode | null | undefined,
  key: string,
  params?: TranslationParams,
  fallback?: string,
): string {
  const language = getLanguage(source);
  const template = resolveTemplate(language, key, fallback);
  return applyParams(template, params);
}

export function tLines(
  source: Phaser.Scene | LanguageCode | null | undefined,
  lines: string[],
): string[] {
  return lines.map((line) => t(source, line));
}

export function translateDifficulty(
  source: Phaser.Scene | LanguageCode | null | undefined,
  difficulty: StageDifficulty,
): string {
  return t(source, `difficulty.${difficulty}`);
}

export function translateCurrency(
  source: Phaser.Scene | LanguageCode | null | undefined,
  currency: 'gold' | 'heroStone',
): string {
  return t(source, `currency.${currency}`);
}

function getStoredLanguage(): LanguageCode {
  const raw = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return normalizeLanguage(raw);
}

function normalizeLanguage(value: string | null | undefined): LanguageCode {
  switch (value) {
    case 'en':
    case 'ja':
    case 'zh':
    case 'ko':
      return value;
    default:
      return DEFAULT_LANGUAGE;
  }
}

function applyParams(template: string, params?: TranslationParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => {
    const value = params[key];
    return value === null || value === undefined ? '' : String(value);
  });
}

function resolveTemplate(language: LanguageCode, key: string, fallback?: string): string {
  switch (language) {
    case 'ko':
      return KO[key] ?? fallback ?? key;
    case 'en':
      return EN[key] ?? fallback ?? key;
    case 'ja':
      return JA[key] ?? EN[key] ?? fallback ?? KO[key] ?? key;
    case 'zh':
      return ZH[key] ?? EN[key] ?? fallback ?? KO[key] ?? key;
    default:
      return fallback ?? KO[key] ?? key;
  }
}
